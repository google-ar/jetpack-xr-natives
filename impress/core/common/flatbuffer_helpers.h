// Converts a paired vector of Typed IDs into a flatbuffer vector using the
// underlying type. Sfinae on T::ValueType ensures this is only considered
// when T is a TypedId.
template <typename D, typename T, typename R,
          std::enable_if_t<std::is_same<D, typename T::ValueType>{}, int> = 0>
flatbuffers::Offset<flatbuffers::Vector<D>> CreateVector(
    flatbuffers::FlatBufferBuilder& fbb, const PairedVector<T, R>& vector) {
  return fbb.CreateVector(reinterpret_cast<const D*>(vector.data()),
                          vector.size());
}

