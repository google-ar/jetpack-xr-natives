// Specialized ReadFromFlatbuffer for subtypes of flatbuffer::Table
// (i.e. the raw flatbuffer types)
template <class T,
          std::enable_if_t<std::is_base_of<flatbuffers::Table, T>{}, int> = 0>
OptionalError ReadFromFlatbuffer(const uint8_t* flatbuffer, const T** dest) {
  *dest = nullptr;
  if (!flatbuffer) {
    return Error("Internal Error: missing required 'flatbuffer' parameter");
  }
  const T* root = flatbuffers::GetRoot<T>(flatbuffer);
  if (root == nullptr) {
    return Error("Internal Error: flatbuffer root type mismatch");
  }
  *dest = root;

  return NoError();
}

template <class T,
          std::enable_if_t<std::is_base_of<flatbuffers::Table, T>{}, int> = 0>
OptionalError GetRoot(const BufferAccess& flatbuffer, const T** dest) {
  *dest = nullptr;
  if (flatbuffer.Empty()) {
    return Error("Provided buffer is empty");
  }
  const T* root = flatbuffers::GetRoot<T>(flatbuffer.Data());
  if (root == nullptr) {
    return Error("Flatbuffer root type mismatch");
  }
  *dest = root;

  return NoError();
}

// Specialized ReadFromFlatbuffer for subtypes of flatbuffer::NativeTable
// (i.e. the flatbuffer object-api types)
template <class T, std::enable_if_t<
                       std::is_base_of<flatbuffers::NativeTable, T>{}, int> = 0>
OptionalError ReadFromFlatbuffer(const uint8_t* flatbuffer, T* dest) {
  const typename T::TableType* table;
  MP_RETURN_IF_ERROR(ReadFromFlatbuffer(flatbuffer, &table));
  table->UnPackTo(dest);
  return NoError();
}

// Serialize `source` (a *DefT generated by flatbuffers) to a binary stream.
template <class T, std::enable_if_t<
                       std::is_base_of<flatbuffers::NativeTable, T>{}, int> = 0>
OptionalError WriteToFlatbuffer(T* source, BufferAccess* access) {
  if (!source) {
    return Error("Internal Error: missing required 'source' parameter");
  }
  if (!access) {
    return Error("Internal Error: missing required 'flatbuffer' parameter");
  }
  flatbuffers::FlatBufferBuilder fbb(1024);
  fbb.Finish(T::TableType::Pack(fbb, source));

  const uint8_t* data = fbb.GetBufferPointer();
  const size_t size = fbb.GetSize();

  if (!size) {
    return Error("Internal error: Failed to convert object to flatbuffer");
  }

  *access = BufferAccess::Clone(data, size);
  return NoError();
}

// Release the memory owned by a flatbuffer builder into a buffer access.
OptionalError ReleaseToBufferAccess(flatbuffers::FlatBufferBuilder* fbb,
                                    BufferAccess* access);

// Release the memory owned by a flatbuffer parser (which just uses a builder).
inline OptionalError ReleaseToBufferAccess(flatbuffers::Parser* parser,
                                           BufferAccess* access) {
  return ReleaseToBufferAccess(&parser->builder_, access);
}

inline BufferAccess WrappedAccess(const flatbuffers::Vector<uint8_t>* vec) {
  return BufferAccess::Wrap(vec->Data(), vec->size());
}

// Helper type to wrap a pointer to a flatbuffer struct along with a buffer
// access that contains that pointer within it's view.
template <typename T>
class FlatBufferAccess {
 public:
  // Default-construct to empty state.
  FlatBufferAccess() : root_(nullptr), buffer_() {}

  // Manual construction for when root != GetRoot(), e.g. nested flatbuffers.
  FlatBufferAccess(const T* root, BufferAccess buffer)
      : root_(root), buffer_(std::move(buffer)) {}

  // Helper method to steal a builder's constructed buffer and it's root.
  friend inline OptionalError CreateFlatBufferAccess(
      flatbuffers::FlatBufferBuilder* fbb, FlatBufferAccess<T>* out_access) {
    BufferAccess buffer;
    MP_RETURN_IF_ERROR(ReleaseToBufferAccess(fbb, &buffer));
    MP_RETURN_IF_ERROR(CreateFlatBufferAccess(std::move(buffer), out_access));
    return NoError();
  }
  // Helper method to get access to the root structure in a buffer.
  friend inline OptionalError CreateFlatBufferAccess(
      BufferAccess buffer, FlatBufferAccess<T>* out_access) {
    const T* root = nullptr;
    MP_RETURN_IF_ERROR(GetRoot(buffer, &root));
    *out_access = FlatBufferAccess{root, std::move(buffer)};
    return NoError();
  }
  static FlatBufferAccess<T> CloneNestedFlatBuffer(const T* root,
                                                   const uint8_t* data,
                                                   size_t size) {
    size_t offset = reinterpret_cast<const uint8_t*>(root) - data;
    assert(offset < size);
    BufferAccess buffer = BufferAccess::Clone(data, size);
    const T* cloned_root = reinterpret_cast<const T*>(buffer.Data() + offset);
    return FlatBufferAccess<T>(cloned_root, std::move(buffer));
  }
  // Accessors.
  const T* Root() const { return root_; }
  const BufferAccess& Buffer() const { return buffer_; }

  // Convenience operators.
  const T* operator->() const { return Root(); }
  const T* operator*() const { return Root(); }

  // Releases ownership of the contained buffer to the caller.
  BufferAccess&& ReleaseBuffer() { return std::move(buffer_); }

 private:
  const T* root_ = nullptr;
  BufferAccess buffer_;
};

